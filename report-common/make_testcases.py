"""Generate the reports' test-case table from the test suite itself.

The table is not written by hand: it is read from `code/`, so it cannot drift
from what actually runs in CI. Each test function becomes one case. The
description is the test's docstring where it has one, otherwise its name
turned back into a sentence, and the status comes from a real pytest run.

Run from the repository root:

    python report-common/make_testcases.py

It writes `report-common/test-cases.tex`, which every report \\input's.
"""
from __future__ import annotations

import ast
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODE = os.path.join(ROOT, "code")
OUT = os.path.join(ROOT, "report-common", "test-cases.tex")
PYTHON = os.path.join(CODE, ".venv", "bin", "python")

# Test file -> (component shown in the table, how the area is described)
AREAS = {
    "trimmer/tests/test_trimmer.py": "Trimmer",
    "trimmer/tests/test_benchmark.py": "Trimmer (benchmark)",
    "trimmer/tests/test_projects.py": "Trimmer (second project)",
    "cache/tests/test_cache.py": "Cache",
    "autopilot/tests/test_autopilot.py": "Autopilot",
    "tests/test_integration.py": "Gateway (end to end)",
    "tests/test_dashboard.py": "Gateway (dashboard)",
}

TEX_ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def tex(text: str) -> str:
    return "".join(TEX_ESCAPES.get(ch, ch) for ch in text)


def humanise(name: str) -> str:
    """test_cache_hit_sends_nothing -> 'Cache hit sends nothing'."""
    words = name[len("test_"):].replace("_", " ").strip() if name.startswith("test_") else name
    return words[:1].upper() + words[1:]


def describe(node: ast.FunctionDef) -> str:
    """First sentence of the docstring, else the name as a sentence."""
    doc = ast.get_docstring(node)
    if not doc:
        return humanise(node.name)
    first = re.split(r"(?<=[.?!])\s", " ".join(doc.split()))[0]
    return first.rstrip(".")


def statuses() -> dict[str, str]:
    """nodeid -> PASSED / SKIPPED / FAILED, from a real run."""
    exe = PYTHON if os.path.exists(PYTHON) else sys.executable
    proc = subprocess.run(
        [exe, "-m", "pytest", "-p", "no:cacheprovider", "--tb=no", "-v"],
        cwd=CODE, capture_output=True, text=True,
    )
    found: dict[str, str] = {}
    for line in proc.stdout.splitlines():
        # a parametrised id can contain spaces, e.g. "...[fix parse_row]"
        m = re.match(r"^(\S+::.*?)\s+(PASSED|SKIPPED|FAILED|XFAIL)\b", line.strip())
        if m:
            found[m.group(1)] = m.group(2)
    return found


def collect() -> list[tuple[str, str, str, str]]:
    """(area, case, expected result, status) for every test, in report order."""
    result = statuses()
    rows: list[tuple[str, str, str, str]] = []
    for rel, area in AREAS.items():
        path = os.path.join(CODE, rel)
        if not os.path.exists(path):
            continue
        tree = ast.parse(open(path, encoding="utf-8").read())
        for node in tree.body:
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if not node.name.startswith("test_"):
                continue
            nodeid = f"{rel}::{node.name}"
            raw = result.get(nodeid, "")
            if not raw:  # parametrised cases appear as name[param]
                matches = [v for k, v in result.items() if k.startswith(nodeid + "[")]
                raw = "SKIPPED" if matches and all(m == "SKIPPED" for m in matches) else (
                    "PASSED" if matches else "not run")
            status = {"PASSED": "Pass", "SKIPPED": "Skip", "FAILED": "FAIL"}.get(raw, raw)
            rows.append((area, describe(node), humanise(node.name), status))
    return rows


def render(rows: list[tuple[str, str, str, str]]) -> str:
    total = len(rows)
    passed = sum(1 for r in rows if r[3] == "Pass")
    skipped = sum(1 for r in rows if r[3] == "Skip")

    out: list[str] = []
    out.append("% Generated by report-common/make_testcases.py -- do not edit by hand.\n")
    out.append(
        f"The suite has {total} automated test cases: {passed} pass and {skipped} are "
        "skipped (they need the optional embedding model, which is not installed in "
        "CI). Every case runs on each pull request and on each push to "
        "\\code{master}. The table below is generated from the test suite itself by "
        "\\code{report-common/make\\_testcases.py}, so it cannot drift from what "
        "actually runs.\n\n")

    # ragged right: justifying these narrow columns only produces underfull boxes
    col = "\\raggedright\\arraybackslash"
    out.append(f"\\begin{{longtable}}{{@{{}}>{{{col}}}p{{0.085\\textwidth}}"
               f">{{{col}}}p{{0.19\\textwidth}}"
               f">{{{col}}}p{{0.475\\textwidth}}"
               f">{{{col}}}p{{0.09\\textwidth}}@{{}}}}\n")
    out.append("\\toprule\n\\textbf{ID} & \\textbf{Area} & \\textbf{Test case} & "
               "\\textbf{Result} \\\\\n\\midrule\n\\endfirsthead\n")
    out.append("\\toprule\n\\textbf{ID} & \\textbf{Area} & \\textbf{Test case} & "
               "\\textbf{Result} \\\\\n\\midrule\n\\endhead\n")
    out.append("\\midrule\n\\multicolumn{4}{r@{}}{\\small\\itshape continued on the "
               "next page}\\\\\n\\endfoot\n\\bottomrule\n\\endlastfoot\n")

    last_area = None
    for i, (area, desc, _name, status) in enumerate(rows, start=1):
        shown = area if area != last_area else ""
        last_area = area
        out.append(f"TC-{i:02d} & {tex(shown)} & {tex(desc)} & {status} \\\\\n")

    out.append("\\caption{Automated test cases and their results.}\n")
    out.append("\\label{tab:testcases}\n")
    out.append("\\end{longtable}\n")
    return "".join(out)


def main() -> None:
    rows = collect()
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render(rows))
    passed = sum(1 for r in rows if r[3] == "Pass")
    print(f"wrote {OUT}: {len(rows)} cases, {passed} passing")


if __name__ == "__main__":
    main()
